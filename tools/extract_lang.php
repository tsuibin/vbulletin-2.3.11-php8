<?php
/**
 * Extract every translatable UI string from the vBulletin templates.
 * Writes admin/lang_en.php (key = English source text, value = English).
 *
 * Usage: php tools/extract_lang.php
 */
require_once __DIR__ . '/../admin/php8compat.php';
require_once __DIR__ . '/../admin/db_mysql.php';

$db = new DB_Sql_vb;
$db->server = '127.0.0.1'; $db->user = 'root'; $db->password = '';
$db->database = 'vbulletin'; $usepconnect = 0; $db->connect();

$stop = array_flip(array('the','a','an','and','or','of','to','in','on','for','is','are','be','it','this','that','with','by','as','at','from','no','yes','here'));

function vb_extract_candidate($t, $stop) {
    $t = trim(preg_replace('/\s+/', ' ', $t));
    if (strpos($t, '&gt;') !== false || strpos($t, '&lt;') !== false) return false;
    if ($t === '' || strlen($t) < 2 || strlen($t) > 80) return false;
    if (strpos($t, '$') !== false || strpos($t, '{') !== false) return false;
    if (!preg_match('/[A-Za-z]{2,}/', $t)) return false;
    if (preg_match('/^&[a-z]+;$/i', $t)) return false;
    $words = preg_split('/\s+/', $t);
    if (count($words) < 2 && !preg_match('/^[A-Z][A-Za-z]{2,}$/', $t)) return false;
    if (isset($stop[strtolower($t)])) return false;
    return true;
}

function vb_extract_from_html($html, &$out, $stop) {
    $html = preg_replace('/<!--.*?-->/s', '', $html);
    $html = preg_replace('/]*>.*?<\/script>/is', '', $html);
    $html = preg_replace('/<style\b[^>]*>.*?<\/style>/is', '', $html);
    $html = preg_replace('/<textarea\b[^>]*>.*?<\/textarea>/is', '', $html);
    $parts = preg_split('/(<[^>]+>)/', $html, -1, PREG_SPLIT_DELIM_CAPTURE);
    foreach ($parts as $i => $seg) {
        if ($i % 2 == 1) continue;
        if (vb_extract_candidate($seg, $stop)) {
            $out[trim(preg_replace('/\s+/', ' ', $seg))] = true;
        }
    }
    if (preg_match_all('/\b(value|alt|title|placeholder)\s*=\s*"([^"]*)"/i', $html, $m)) {
        foreach ($m[2] as $v) {
            if (vb_extract_candidate($v, $stop)) {
                $out[trim(preg_replace('/\s+/', ' ', $v))] = true;
            }
        }
    }
}

$out = array();
$r = $db->query("SELECT title,template FROM template WHERE templatesetid IN (-1,1)");
while ($row = $db->fetch_array($r)) {
    vb_extract_from_html($row['template'], $out, $stop);
}
$keys = array_keys($out);
sort($keys, SORT_STRING | SORT_FLAG_CASE);

$lines = array();
$lines[] = '<?php';
$lines[] = '// AUTO-GENERATED by tools/extract_lang.php — do not edit by hand.';
$lines[] = '// Canonical list of every UI string found in the vBulletin templates.';
$lines[] = '// lang_zh.php overrides these by key; missing keys fall back to English.';
$lines[] = 'return array(';
foreach ($keys as $k) {
    $lines[] = '    ' . var_export($k, true) . ' => ' . var_export($k, true) . ',';
}
$lines[] = ');';
file_put_contents(__DIR__ . '/../admin/lang_en.php', implode("\n", $lines) . "\n");
echo "extracted: " . count($keys) . " strings\n";

